/**
 * 动态根据词组汉字实时推导三版本五笔编码与拼音
 */
export const getDynamicPhrase = (word: string): WubiPhraseData => {
  const pinyin = Array.from(word).map(c => WUBI_CHAR_MAP.get(c)?.pinyin || "").join(" ");
  const code86 = calculatePhraseCode(word, "86");
  const code98 = calculatePhraseCode(word, "98");
  const codeNew = calculatePhraseCode(word, "newCentury");
  const bd = getPhraseBreakdown(word, "86");
  const breakdown = bd.steps.map(s => `${s.char}(${s.keys})`).join(" + ");

  return {
    word,
    pinyin,
    code86,
    code98,
    codeNew,
    breakdown
  };
};

let cachedDynamicPhrases: WubiPhraseData[] | null = null;

/**
 * 获取全量 3,000 高频词组结构化数据（惰性单例缓存）
 */
export const getAllDynamicPhrases = (): WubiPhraseData[] => {
  if (!cachedDynamicPhrases) {
    cachedDynamicPhrases = HIGH_FREQ_PHRASES.map(getDynamicPhrase);
  }
  return cachedDynamicPhrases;
};

/**
 * 按词长筛选词组数据（2: 双字词, 3: 三字词, 4: 四字词）
 */
export const getPhrasesByLength = (len: number): WubiPhraseData[] => {
  return HIGH_FREQ_PHRASES.filter(w => w.length === len).map(getDynamicPhrase);
};
